-- Ortak model (LLM): Studio'nun /api/studio/ekip/llm/jobs işleri ve tek çalıştırıcının yaşam işareti.
--
-- MySQL kaynağı YOK: orkestrai'de işler yalnız model çalışanının belleğinde tutulurdu (api/ajanlar/llm_queue.py),
-- çalışanın hazır olduğu Unix soketi ve ready.json ile anlaşılırdı. Taşıma aracı bu tablolara veri kopyalamaz.
-- Kavram eşlemesi (orkestrai → Peyrev):
--   LLMQueue.jobs[id] (uuid4 hex)                     → llm_isler.id
--   owner (company_id, user_id, session_id)           → (kullanici_id, oturum_id); firma yok
--   request_key + digest (tekrar koruması)            → UNIQUE (kullanici_id, oturum_id, istek_id) + ozet
--   payload / result / error_code                     → istek / sonuc (kanonik JSON baytları) / hata_kodu
--   status, expires_at (gönderim + 300 sn)             → durum, gecerlilik_sonu
--   waiting kuyruğu (FIFO)                            → durum = 'queued', sira sırasıyla
--   worker.sock + ready.json (config_sha256)           → llm_calistirici (son_sinyal + ayar_izi)
--
-- İçerik kalıcı değildir: istek çalıştırıcı işi alınca, sonuç iptalde silinir; iş her durumda gönderimden 300 sn
-- sonra silinir. Tablolar UNLOGGED: içerik WAL'a yazılmaz, çökmeden sonra boşalır (çalışan belleği gibi).
-- Gece yedeği bu tabloların verisini almamalıdır: pg_dump --no-unlogged-table-data.

CREATE UNLOGGED TABLE llm_isler (
    id TEXT PRIMARY KEY CHECK (id ~ '^[0-9a-f]{32}$'),
    sira BIGINT GENERATED BY DEFAULT AS IDENTITY,      -- FIFO sırası (aynı andaki gönderimler dahil)
    kullanici_id BIGINT NOT NULL REFERENCES kullanicilar (id) ON DELETE CASCADE,
    oturum_id TEXT NOT NULL CHECK (oturum_id ~ '^[0-9a-f]{32}$'),
    istek_id TEXT NOT NULL CHECK (istek_id ~ '^[0-9a-f]{32}$'),
    ozet TEXT NOT NULL CHECK (ozet ~ '^[0-9a-f]{64}$'),
    durum TEXT NOT NULL DEFAULT 'queued'
        CHECK (durum IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
    istek BYTEA CHECK (octet_length(istek) <= 65536),  -- yalnız sırada beklerken
    sonuc BYTEA CHECK (octet_length(sonuc) <= 131072), -- yalnız succeeded
    hata_kodu TEXT CHECK (hata_kodu ~ '^[A-Z_]{1,40}$'), -- yalnız failed; metin koddan üretilir
    olusturma TIMESTAMPTZ NOT NULL,
    gecerlilik_sonu TIMESTAMPTZ NOT NULL,
    baslama TIMESTAMPTZ,
    bitis TIMESTAMPTZ,
    UNIQUE (kullanici_id, oturum_id, istek_id),
    CHECK ((durum = 'queued') = (istek IS NOT NULL)),
    CHECK ((durum = 'succeeded') = (sonuc IS NOT NULL)),
    CHECK ((durum = 'failed') = (hata_kodu IS NOT NULL))
);
CREATE INDEX llm_isler_sira_idx ON llm_isler (sira) WHERE durum = 'queued';
CREATE INDEX llm_isler_sure_idx ON llm_isler (gecerlilik_sonu);

-- Tek çalıştırıcı (python -m peyrev.llm.worker) 2 sn'de bir yazar; taze ve aynı ayar izli işaret yoksa API
-- özelliği kapalı sayar.
CREATE UNLOGGED TABLE llm_calistirici (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    ayar_izi TEXT NOT NULL CHECK (ayar_izi ~ '^[0-9a-f]{64}$'),
    baslama TIMESTAMPTZ NOT NULL,
    son_sinyal TIMESTAMPTZ NOT NULL
);
