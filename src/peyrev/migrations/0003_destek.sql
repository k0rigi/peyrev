-- Destek talepleri: Studio'dan öneri, hata bildirimi ve soru; yönetici yanıtları ve ekler. Firma yoktur, talep
-- kullanıcıya bağlıdır. Kurallar peyrev/support/service.py'dedir; bu tablolara yalnız o modül yazar.
--
-- Taşıma (MySQL kaynağı → bu tablolar; taşıma aracı bu eşlemeyi kullanır):
--   SYS_RpaTalepler → destek_talepleri
--     TalepNo → talep_no (korunur)       KullaniciID → kullanici_id (kullanicilar.id = eski KullaniciID)
--     FirmaID → (taşınmaz)               Tur → tur                  Baslik → baslik           Durum → durum
--     AdimTuru → adim_turu               Surum → surum              Platform → platform
--     YayinSurumu → yayin_surumu         SonYazan → son_yazan       Olusturma → olusturma     Guncelleme → guncelleme
--     KullaniciGordu → kullanici_gordu   YoneticiGordu → yonetici_gordu
--   SYS_RpaTalepMesajlari → destek_mesajlari
--     MesajID → id (korunur)   TalepNo → talep_no   YazanID → yazan_id   Yazan → yazan   Metin → metin
--     Olusturma → olusturma
--   SYS_RpaTalepEkleri → destek_ekleri
--     EkID → id (korunur)   TalepNo → talep_no   Tur → tur   Ad → ad   Bicim → bicim   Boyut → boyut
--     Icerik (MEDIUMBLOB) → icerik (bytea)   Olusturma → olusturma
--   Zamanlar: MySQL DATETIME değerleri saat dilimsiz Türkiye saatidir; Europe/Istanbul saati olarak timestamptz'ye
--   çevrilir (SQL'de: değer::timestamp AT TIME ZONE 'Europe/Istanbul'). NULL görülme zamanları NULL kalır.
--   Kullanıcısı kullanicilar'a taşınmamış talep alınamaz (yabancı anahtar); mesajlar ve ekler talepleriyle gelir.
--   Taşıma bitince yeni talepler en büyük numaranın üstünden sürsün:
--     SELECT setval(pg_get_serial_sequence('destek_talepleri', 'talep_no'),
--                   GREATEST(1000, (SELECT coalesce(max(talep_no), 0) FROM destek_talepleri)));

CREATE TABLE destek_talepleri (
    talep_no INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    kullanici_id BIGINT NOT NULL REFERENCES kullanicilar (id) ON DELETE CASCADE,
    tur TEXT NOT NULL CHECK (tur IN ('adim_onerisi', 'adim_iyilestirme', 'hata', 'soru', 'diger')),
    baslik TEXT NOT NULL CHECK (length(baslik) BETWEEN 1 AND 120),
    durum TEXT NOT NULL DEFAULT 'acik'
        CHECK (durum IN ('acik', 'inceleniyor', 'yanitlandi', 'planlandi', 'yayinlandi', 'kapandi')),
    adim_turu TEXT CHECK (adim_turu IS NULL OR length(adim_turu) <= 100),
    surum TEXT NOT NULL CHECK (length(surum) <= 20),
    platform TEXT NOT NULL CHECK (length(platform) <= 20),
    yayin_surumu TEXT CHECK (yayin_surumu IS NULL OR length(yayin_surumu) <= 20),
    son_yazan TEXT NOT NULL DEFAULT 'kullanici' CHECK (son_yazan IN ('kullanici', 'yonetici')),
    olusturma TIMESTAMPTZ NOT NULL DEFAULT now(),
    guncelleme TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Okunmamış: son yazan karşı taraf ve guncelleme bu taraf en son baktığından sonra (NULL: hiç bakmadı).
    kullanici_gordu TIMESTAMPTZ,
    yonetici_gordu TIMESTAMPTZ,
    -- Yayın sürümü yalnız "yayınlandı" durumunda tutulur.
    CHECK (yayin_surumu IS NULL OR durum = 'yayinlandi')
);
CREATE INDEX destek_talepleri_kullanici_idx ON destek_talepleri (kullanici_id, guncelleme DESC);
CREATE INDEX destek_talepleri_durum_idx ON destek_talepleri (durum, guncelleme DESC);

CREATE TABLE destek_mesajlari (
    -- Zamana göre sıralanan kimlik: aynı anda yazılan mesajlar da yazıldığı sırayla gösterilir.
    id TEXT PRIMARY KEY CHECK (id ~ '^[0-9a-f]{32}$'),
    talep_no INTEGER NOT NULL REFERENCES destek_talepleri (talep_no) ON DELETE CASCADE,
    -- Yazan kullanıcı ya da yanıtlayan yönetici; yabancı anahtar yok: yönetici hesabı kalksa da yanıt kalır.
    yazan_id BIGINT NOT NULL,
    yazan TEXT NOT NULL CHECK (yazan IN ('kullanici', 'yonetici')),
    metin TEXT NOT NULL CHECK (length(metin) BETWEEN 1 AND 5000),
    olusturma TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX destek_mesajlari_talep_idx ON destek_mesajlari (talep_no, olusturma);
CREATE INDEX destek_mesajlari_yazan_idx ON destek_mesajlari (yazan_id, olusturma);

CREATE TABLE destek_ekleri (
    id TEXT PRIMARY KEY CHECK (id ~ '^[0-9a-f]{32}$'),
    talep_no INTEGER NOT NULL REFERENCES destek_talepleri (talep_no) ON DELETE CASCADE,
    tur TEXT NOT NULL CHECK (tur IN ('akis', 'hata_kaydi', 'gorsel')),
    ad TEXT NOT NULL CHECK (length(ad) BETWEEN 1 AND 120),
    -- Panel görselleri satır içi gösterir: yalnız bu üç biçim saklanır.
    bicim TEXT NOT NULL CHECK (bicim IN ('application/json', 'image/png', 'image/jpeg')),
    boyut INTEGER NOT NULL,
    icerik BYTEA NOT NULL,
    olusturma TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (boyut = octet_length(icerik))
);
CREATE INDEX destek_ekleri_talep_idx ON destek_ekleri (talep_no);
